// Writes web/src/abi.ts from the Hardhat artifacts (run `npx hardhat compile` first).
//   node web/gen-abi.mjs
// The account's custom errors are raised inside the external libraries too, so their error fragments are merged
// into one list the app uses to decode reverts.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const art = (name) => JSON.parse(fs.readFileSync(path.join(ROOT, "artifacts", "contracts", "account", `${name}.sol`, `${name}.json`), "utf8")).abi;

const account = art("EncryptedAccount");
const factory = art("EncryptedAccountFactory");
const seen = new Set();
const errors = [];
for (const name of ["EncryptedAccount", "PinLib", "PolicyLib", "OpsLib", "OpenLib"]) {
  for (const f of art(name)) {
    if (f.type !== "error") continue;
    const sig = `${f.name}(${f.inputs.map((i) => i.type).join(",")})`;
    if (!seen.has(sig)) {
      seen.add(sig);
      errors.push(f);
    }
  }
}
const out = `// Generated by web/gen-abi.mjs from the Hardhat artifacts. Do not edit by hand.
export const ACCOUNT_ABI = ${JSON.stringify(account)} as const;
export const FACTORY_ABI = ${JSON.stringify(factory)} as const;
export const ERRORS_ABI = ${JSON.stringify(errors)} as const;
`;
fs.writeFileSync(path.join(HERE, "src", "abi.ts"), out);
console.log(`abi.ts: account ${account.length} entries, factory ${factory.length}, errors ${errors.length}`);
